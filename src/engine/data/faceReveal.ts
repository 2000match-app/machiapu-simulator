import type { Gender } from '../types';

export interface FacePhoto {
  id: string;
  file: string;
  gender: Gender;
  /** 見た目からの推定年齢（仮） */
  age: number;
  /** 元のファイル名（顔かくしフォルダ） */
  source: string;
}

const f = (n: number, gender: Gender, age: number, source: string): FacePhoto => {
  const id = `h${String(n).padStart(2, '0')}`;
  return { id, file: `${id}.jpg`, gender, age, source };
};


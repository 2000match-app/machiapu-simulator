export function eventName(id: string): string {
  return EVENTS.find((e) => e.id === id)?.name ?? id;
}

/** プレイ中の表示名。真因が分からない出来事は、見えている状態で表す（結果画面では eventName を使う） */
export function eventVisibleName(id: string): string {
  const e = EVENTS.find((x) => x.id === id);
  return e?.visible ?? e?.name ?? id;
}

export function getEvent(id: string): EventDef {
  const e = EVENTS.find((x) => x.id === id);
  if (!e) throw new Error(`unknown event ${id}`);
  return e;
}

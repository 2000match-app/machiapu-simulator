export const PORTRAIT_SPECS: PortraitSpec[] = CHARACTERS.map((c) => ({
  id: c.id,
  name: c.name,
  gender: c.gender,
  age: c.age,
  looks: c.looks,
  heightCm: c.heightCm,
  photoInitiallyVisible: c.photoInitiallyVisible,
  ...DESIGN[c.id],
}));

export function buildPrompt(spec: PortraitSpec, revisionNote?: string): string {
  const who = `${spec.age}歳の${spec.gender === 'M' ? '男性' : '女性'}。身長${spec.heightCm}cm、${spec.build}。`;
  return [
    COMMON_PROMPT,
    `\n\n人物：${who}`,
    `\n顔立ち：${spec.face}。`,
    `\n印象：${LEVEL_IMPRESSION[spec.looks]}。`,
    `\n髪型：${spec.hair}。`,
    `\n服装：${spec.clothing}。`,
    `\n避けること：${spec.avoid}`,
    revisionNote ? `\n\n前回からの修正点：${revisionNote}` : '',
  ].join('');
}

